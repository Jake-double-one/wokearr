#!/usr/bin/env python3
"""
Writes licenses.txt: the licenses of everything Wokearr ships in its image -
the Python packages from requirements.txt including what they pull in, read
from the installed package metadata, plus the non-Python parts.

Runs inside the built image, where exactly those packages are installed:

    docker build -t wokearr:dev .
    docker run --rm --entrypoint python -v "$PWD:/src" wokearr:dev \\
        /src/tools/licenses.py /src/requirements.txt > licenses.txt

With --check FILE it only compares the overview against FILE and fails when
a package or license changed (CI does that, see tests.yml). Versions are
deliberately left out, so routine updates don't make the file stale.
"""
import importlib.metadata as md
import re
import sys
import textwrap

from pip._vendor.packaging.requirements import Requirement

# Not Python packages, so not in any metadata - kept by hand
OTHER_COMPONENTS = [
    ("Python", "PSF-2.0", "https://docs.python.org/3/license.html",
     "Interpreter and standard library (base image python:3.12-slim)."),
    ("DejaVu fonts", "Bitstream-Vera AND LicenseRef-DejaVu-public-domain",
     "https://dejavu-fonts.github.io/License.html",
     "Font of the badge label (Debian package fonts-dejavu-core); full text in the "
     "image at /usr/share/doc/fonts-dejavu-core/copyright."),
    ("tzdata", "LicenseRef-Public-Domain", "https://www.iana.org/time-zones",
     "Time zone database (Debian package tzdata)."),
    ("Debian base system", "various (mostly GPL/LGPL/BSD/MIT)", "https://www.debian.org/legal/licenses/",
     "Operating system of the base image; each package's terms are in the image "
     "at /usr/share/doc/<package>/copyright."),
]

_LICENSE_FILE = re.compile(r"(^|/)(LICEN[CS]E|COPYING|NOTICE)[^/]*$", re.I)
_URL_LABELS = ("source", "repository", "homepage", "home", "code")
# An SPDX id or expression, as many packages put into the License field
_SPDX = re.compile(r"^[A-Za-z0-9.+-]+( (AND|OR|WITH) [A-Za-z0-9.+-]+)*$")
# Trove classifiers that name exactly one license
_CLASSIFIER_SPDX = {"MIT License": "MIT", "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0"}


def _key(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _closure(requirements_file: str) -> dict:
    """Every installed distribution requirements.txt pulls in, by name."""
    found = {}

    def walk(name: str) -> None:
        if _key(name) in found:
            return
        dist = md.distribution(name)
        found[_key(name)] = dist
        for raw in dist.requires or []:
            req = Requirement(raw)
            if req.marker and not req.marker.evaluate({"extra": ""}):
                continue
            walk(req.name)

    with open(requirements_file, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                walk(Requirement(line).name)
    return dict(sorted(found.items()))


def _license(dist) -> str:
    meta = dist.metadata
    if meta.get("License-Expression"):
        return meta["License-Expression"]
    if _SPDX.match((meta.get("License") or "").strip()):
        return meta["License"].strip()
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                   if c.startswith("License ::")]
    classifiers = [_CLASSIFIER_SPDX.get(c, c) for c in classifiers]
    if classifiers:
        return " / ".join(classifiers)
    return (meta.get("License") or "see license text").splitlines()[0][:60]


def _url(dist) -> str:
    meta = dist.metadata
    urls = {}
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        urls[label.strip().lower()] = url.strip()
    for label in _URL_LABELS:
        if label in urls:
            return urls[label]
    return meta.get("Home-page") or next(iter(urls.values()), "")


def _license_texts(dist) -> list:
    texts = []
    for file in dist.files or []:
        if _LICENSE_FILE.search(str(file)) and ".dist-info/" in str(file):
            texts.append((str(file).split("/")[-1], file.read_text(encoding="utf-8").strip()))
    return texts


def overview(dists: dict) -> list:
    return [(dist.metadata["Name"], _license(dist), _url(dist)) for dist in dists.values()]


def render(dists: dict) -> str:
    rule = "=" * 78
    out = [
        "Wokearr - third-party licenses",
        "",
        "Wokearr itself is MIT-licensed (see LICENSE). Its container image also",
        "contains the components below, each under its own license. Scores and",
        "review links come from isitwokeornot.com and are not covered here.",
        "",
        "Generated by tools/licenses.py from the installed package metadata.",
        "",
        rule,
        "Python packages (requirements.txt and their dependencies)",
        rule,
        "",
    ]
    for name, license_, url in overview(dists):
        out += [f"{name} - {license_}", f"  {url}"]
    out += ["", rule, "Other components of the image", rule, ""]
    for name, license_, url, note in OTHER_COMPONENTS:
        out += [f"{name} - {license_}", f"  {url}"]
        out += textwrap.wrap(note, 78, initial_indent="  ", subsequent_indent="  ")
        out.append("")
    out += [rule, "License texts", rule]
    for dist in dists.values():
        for filename, text in _license_texts(dist):
            out += ["", "-" * 78, f"{dist.metadata['Name']} - {filename}", "-" * 78, "", text]
    return "\n".join(out) + "\n"


def check(dists: dict, path: str) -> int:
    with open(path, encoding="utf-8") as f:
        current = f.read()
    expected = render(dists)
    head = expected.split("Other components of the image")[0]
    if head not in current:
        print(f"{path} is out of date - a package or its license changed. Regenerate it, "
              "see tools/licenses.py.", file=sys.stderr)
        return 1
    print(f"{path} is up to date.")
    return 0


def main(argv: list) -> int:
    if len(argv) >= 3 and argv[0] == "--check":
        return check(_closure(argv[2]), argv[1])
    if len(argv) == 1:
        sys.stdout.write(render(_closure(argv[0])))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
